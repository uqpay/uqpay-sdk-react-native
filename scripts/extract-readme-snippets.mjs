#!/usr/bin/env node
/**
 * Extract every tagged code sample from the merchant-facing docs into
 * `docs-fixtures/`, so `tsc -p docs-fixtures` can prove they compile (AC RN-DOC1).
 *
 * A sample is extracted when an HTML comment of the form
 *
 *     <!-- snippet: quickstart -->
 *     ```ts
 *     ...
 *     ```
 *
 * immediately precedes a ```ts or ```tsx fence. The block is written verbatim to
 * `docs-fixtures/quickstart.ts` (or `.tsx`), which resolves `@uqpay/react-native`
 * back to `src/index.ts` through the fixture tsconfig's `paths` mapping — so a
 * sample cannot drift from the real API without the build going red.
 *
 * Untagged fences are ignored on purpose: not every sample in the docs is
 * TypeScript the merchant pastes (shell, JSON, XML, and deliberately-wrong code
 * all appear).
 */

import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'docs-fixtures');

/** Files that are hand-written and must survive the clean. */
const KEEP = new Set(['tsconfig.json', 'prelude.d.ts', 'README.md']);

/** `<!-- snippet: name -->` then an optional blank line then a ts/tsx fence. */
const TAGGED = /<!--\s*snippet:\s*([a-z0-9][a-z0-9-]*)\s*-->\s*\n+```(tsx?)\n([\s\S]*?)\n```/g;

/** A tag with no usable fence after it is a typo, not a silent no-op. */
const ORPHAN = /<!--\s*snippet:\s*([a-z0-9][a-z0-9-]*)\s*-->(?!\s*\n+```tsx?\n)/g;

function docSources() {
  const files = [join(root, 'README.md')];
  for (const entry of readdirSync(join(root, 'docs'), { withFileTypes: true })) {
    // `docs/internal/**` is our own working notes; it is never published and
    // never extracted.
    if (entry.isFile() && entry.name.endsWith('.md')) {
      files.push(join(root, 'docs', entry.name));
    }
  }
  return files;
}

function clean() {
  mkdirSync(outDir, { recursive: true });
  for (const entry of readdirSync(outDir, { withFileTypes: true })) {
    if (entry.isFile() && !KEEP.has(entry.name)) {
      rmSync(join(outDir, entry.name));
    }
  }
}

function main() {
  clean();

  /** @type {Map<string, string>} name → the doc it came from, for duplicate detection. */
  const seen = new Map();
  const problems = [];
  let written = 0;

  for (const file of docSources()) {
    const markdown = readFileSync(file, 'utf8');
    const rel = file.slice(root.length + 1);

    for (const [, name] of markdown.matchAll(ORPHAN)) {
      problems.push(`${rel}: snippet "${name}" is not followed by a \`\`\`ts or \`\`\`tsx fence`);
    }

    for (const [, name, lang, body] of markdown.matchAll(TAGGED)) {
      const previous = seen.get(name);
      if (previous !== undefined) {
        problems.push(`duplicate snippet name "${name}" in ${rel} (already used in ${previous})`);
        continue;
      }
      seen.set(name, rel);

      const header =
        `// Generated by scripts/extract-readme-snippets.mjs from ${rel} — do not edit.\n` +
        `// Snippet: ${name}\n\n`;
      writeFileSync(join(outDir, `${name}.${lang}`), `${header}${body}\n`, 'utf8');
      written += 1;
    }
  }

  if (problems.length > 0) {
    for (const problem of problems) console.error(`error  ${problem}`);
    process.exitCode = 1;
    return;
  }

  if (written === 0) {
    console.error('error  no tagged snippets found — did the tag syntax change?');
    process.exitCode = 1;
    return;
  }

  console.log(`extracted ${written} snippet${written === 1 ? '' : 's'} to docs-fixtures/`);
}

main();
